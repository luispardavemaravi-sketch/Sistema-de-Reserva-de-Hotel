
    create table acompanante (
        id_acompanante bigint generated by default as identity,
        id_reserva bigint not null,
        documento_identidad varchar(20) not null,
        parentesco varchar(50) not null check ((parentesco in ('CONYUGE','HIJO_A','PADRE_MADRE','HERMANO_A','AMIGO_A','COLEGA','ESPOSO','ESPOSA','HIJO','OTRO'))),
        apellidos varchar(100) not null,
        nombre_completo varchar(100) not null,
        primary key (id_acompanante)
    );

    create table area_hotel (
        id_area_hotel bigint generated by default as identity,
        nombre_area varchar(100) not null unique,
        ubicacion varchar(100) not null,
        primary key (id_area_hotel)
    );

    create table caja (
        esta_abierta boolean not null,
        fecha date not null,
        monto_apertura numeric(10,2) not null,
        monto_cierre numeric(10,2),
        id_caja bigint generated by default as identity,
        id_empleado bigint not null,
        primary key (id_caja)
    );

    create table catalogo_servicio (
        precio_vigente numeric(10,2) not null,
        id_catalogo bigint generated by default as identity,
        id_servicio bigint not null,
        categoria varchar(50) not null check ((categoria in ('RESTAURANTE','SPA_Y_BIENESTAR','TRANSPORTE','LIMPIEZA','ENTRETENIMIENTO','OTROS'))),
        primary key (id_catalogo)
    );

    create table check_in (
        fecha_hora_real_entrada timestamp(6) not null,
        id_check_in bigint generated by default as identity,
        id_reserva bigint not null unique,
        observaciones varchar(255),
        primary key (id_check_in)
    );

    create table check_out (
        multa_por_retraso numeric(10,2) not null,
        fecha_hora_real_salida timestamp(6) not null,
        id_check_out bigint generated by default as identity,
        id_reserva bigint not null unique,
        observaciones varchar(500),
        primary key (id_check_out)
    );

    create table comprobante_pago (
        monto_total numeric(10,2) not null,
        fecha_emision timestamp(6) not null,
        id_comprobante bigint generated by default as identity,
        id_reserva bigint not null unique,
        numero_serie varchar(20) not null unique,
        primary key (id_comprobante)
    );

    create table consumo_servicio (
        cantidad integer not null,
        sub_total numeric(10,2) not null,
        fecha_hora timestamp(6) not null,
        id_consumo bigint generated by default as identity,
        id_reserva bigint not null,
        id_servicio bigint not null,
        primary key (id_consumo)
    );

    create table detalle_comprobante (
        cantidad integer not null,
        precio_unitario numeric(10,2) not null,
        subtotal_linea numeric(10,2) not null,
        id_comprobante bigint not null,
        id_detalle bigint generated by default as identity,
        descripcion varchar(255) not null,
        primary key (id_detalle)
    );

    create table empleado (
        estado_activo boolean not null,
        created_date timestamp(6) not null,
        id_empleado bigint generated by default as identity,
        id_turno bigint not null,
        modified_date timestamp(6),
        telefono varchar(20) not null,
        cargo varchar(50) not null check ((cargo in ('RECEPCIONISTA','GERENTE','CONSERJE','PERSONAL_LIMPIEZA','SEGURIDAD','ADMINISTRATIVO'))),
        especialidad varchar(50) not null check ((especialidad in ('ATENCION_AL_CLIENTE','MANTENIMIENTO','ADMINISTRACION','LIMPIEZA_GENERAL','TECNOLOGIAS_INFORMACION'))),
        apellido varchar(100) not null,
        ciudad varchar(100) not null,
        nombre varchar(100) not null,
        email varchar(150) not null unique,
        created_by varchar(255) not null,
        direccion varchar(255) not null,
        modified_by varchar(255),
        primary key (id_empleado)
    );

    create table equipamiento (
        costo_adicional numeric(10,2) not null,
        id_equipamiento bigint generated by default as identity,
        nombre varchar(100) not null unique,
        primary key (id_equipamiento)
    );

    create table estado_habitacion (
        es_reservable boolean not null,
        id_estado bigint generated by default as identity,
        nombre_estado varchar(40) not null unique,
        primary key (id_estado)
    );

    create table estado_reserva (
        es_modificable boolean not null,
        id_estado bigint generated by default as identity,
        nombre_estado varchar(50) not null unique,
        primary key (id_estado)
    );

    create table habitacion (
        estado_activo boolean not null,
        precio_actual numeric(10,2) not null,
        id_estado_habitacion bigint,
        id_habitacion bigint generated by default as identity,
        id_piso bigint,
        id_tipo bigint,
        numero_habitacion varchar(100) not null unique,
        descripcion varchar(255),
        primary key (id_habitacion)
    );

    create table habitacion_equipamiento (
        id_equipamiento bigint not null,
        id_habitacion bigint not null,
        primary key (id_equipamiento, id_habitacion)
    );

    create table huesped (
        estado_activo boolean not null,
        id_huesped bigint generated by default as identity,
        documento_identidad varchar(20) not null unique,
        telefono varchar(20),
        apellidos varchar(100) not null,
        nombre varchar(100) not null,
        email varchar(150) not null unique,
        primary key (id_huesped)
    );

    create table impuesto (
        porcentaje numeric(5,2) not null,
        id_impuesto bigint generated by default as identity,
        nombre_impuesto varchar(50) not null unique,
        primary key (id_impuesto)
