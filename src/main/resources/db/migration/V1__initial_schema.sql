    create table metodo_pago (
        es_digital boolean not null,
        id_metodo bigint generated by default as identity,
        nombre_metodo varchar(50) not null unique,
        primary key (id_metodo)
    );

    create table piso (
        numero_piso integer not null unique,
        id_piso bigint generated by default as identity,
        sector varchar(50) not null,
        primary key (id_piso)
    );

    create table precio_habitacion (
        fecha_fin date not null,
        fecha_inicio date not null,
        monto numeric(10,2) not null,
        id_habitacion bigint not null,
        id_precio bigint generated by default as identity,
        primary key (id_precio)
    );

    create table promocion (
        fecha_caducidad date not null,
        porcentaje_descuento numeric(5,2) not null,
        id_promocion bigint generated by default as identity,
        codigo_cupon varchar(20) not null unique,
        primary key (id_promocion)
    );

    create table reserva (
        fecha_entrada_planificada date not null,
        fecha_salida_planificada date not null,
        monto_total_estimado numeric(10,2) not null,
        created_date timestamp(6) not null,
        fecha_reserva timestamp(6) not null,
        id_estado_reserva bigint not null,
        id_habitacion bigint not null,
        id_huesped bigint not null,
        id_reserva bigint generated by default as identity,
        modified_date timestamp(6),
        codigo_reserva varchar(100) not null unique,
        created_by varchar(255) not null,
        modified_by varchar(255),
        primary key (id_reserva)
    );

    create table servicio_adicional (
        esta_disponible boolean not null,
        id_servicio bigint generated by default as identity,
        nombre varchar(100) not null unique,
        descripcion varchar(255),
        primary key (id_servicio)
    );

    create table tipo_habitacion (
        capacidad_maxima integer not null,
        precio_base numeric(38,2) not null,
        id_tipo bigint generated by default as identity,
        nombre varchar(100) not null unique,
        primary key (id_tipo)
    );

    create table turno (
        hora_final time(0) not null,
        hora_inicio time(0) not null,
        id_turno bigint generated by default as identity,
        primary key (id_turno)
    );

    create table turno_dias (
        id_turno bigint not null,
        dia_semana varchar(255) not null check ((dia_semana in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
        primary key (id_turno, dia_semana)
